const certIdAliases = {
  'oracle-ai': 'CERT-ORACLE-001',
  'bharatcares-internship': 'CERT-BHARATCARES-001',
  'deloitte-simulation': 'CERT-DELOITTE-001',
  'ibm-skillsbuild-ai': 'CERT-COURSERA-IBM-001'
};

export function openCertificateViewer(certId) {
  const resolvedId = certIdAliases[certId] || certId;
  const cert = certificatesData.find(c => c.id === resolvedId);
  if (!cert) return;

  const modalBackdrop = document.getElementById('modalBackdrop');
  const modalWindow = document.getElementById('modalWindow');
  const dynamicContent = document.getElementById('modalDynamicContent');

  if (!modalBackdrop || !modalWindow || !dynamicContent) {
    console.warn('Portfolio modal backdrop elements missing.');
    return;
  }

  const hasVerify = Boolean(cert.verificationUrl);

  const html = `
    <div class="cert-viewer-container">
      <div class="cert-viewer-header">
        <div class="cert-viewer-eyebrow">
          <span>${cert.orderNumber}.</span>
          <span>${cert.category}</span>
          <span>//</span>
          <span>${cert.certificateType}</span>
        </div>
        <h2 class="cert-viewer-title">${cert.title}</h2>
        <div class="cert-viewer-meta-row">
          <span class="cert-viewer-meta-item"><strong>Issuer:</strong> ${cert.issuer}</span>
          <span class="cert-viewer-meta-item"><strong>Recipient:</strong> ${cert.recipient}</span>
          <span class="cert-viewer-meta-item"><strong>Date:</strong> ${cert.completionDate}</span>
          ${cert.credentialId ? `<span class="cert-viewer-meta-item"><strong>Credential ID:</strong> ${cert.credentialId}</span>` : ''}
        </div>
      </div>

      <div class="cert-viewer-stage" id="certViewerStage">
        <img 
          src="${cert.previewImage}" 
          alt="${cert.title} - Official Certificate" 
          class="cert-viewer-doc-img" 
          id="certViewerDocImg"
          title="Click to toggle 1.5x zoom"
        />
        <span class="cert-viewer-zoom-hint">Click image to toggle zoom</span>
      </div>

      <p class="cert-viewer-description">
        ${cert.description}
      </p>

      <div class="cert-viewer-actions">
        <div class="cert-viewer-actions-left">
          <span class="cert-status-dot"></span>
          <span>ORIGINAL DOCUMENT VERIFIED // HARIVANSH VATS</span>
        </div>

        <div class="cert-viewer-actions-right">
          ${hasVerify ? `
            <a href="${cert.verificationUrl}" target="_blank" rel="noopener noreferrer" class="btn-cert-action btn-cert-verify" id="viewerVerifyLink">
              <svg viewBox="0 0 24 24" width="14" height="14" fill="none" stroke="currentColor" stroke-width="2">
                <path d="M10 13a5 5 0 0 0 7.54.54l3-3a5 5 0 0 0-7.07-7.07l-1.72 1.71"></path>
                <path d="M14 11a5 5 0 0 0-7.54-.54l-3 3a5 5 0 0 0 7.07 7.07l1.71-1.71"></path>
              </svg>
              Verify Credential
            </a>
          ` : ''}

          <a href="${cert.filePath}" download="${cert.downloadFilename}" class="btn-cert-action btn-cert-primary" id="viewerDownloadBtn">
            <svg viewBox="0 0 24 24" width="14" height="14" fill="none" stroke="currentColor" stroke-width="2">
              <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"></path>
              <polyline points="7 10 12 15 17 10"></polyline>
              <line x1="12" y1="15" x2="12" y2="3"></line>
            </svg>
            Download Document
          </a>

          <button type="button" class="btn-cert-action btn-cert-secondary" id="certViewerDismissBtn">
            Close Preview
          </button>
        </div>
      </div>
    </div>
  `;

  dynamicContent.innerHTML = html;
  modalWindow.classList.add('modal-wide');
  modalBackdrop.classList.add('active');
  document.body.style.overflow = 'hidden';

  // Toggle Zoom on Document Image
  const docImg = document.getElementById('certViewerDocImg');
  if (docImg) {
    docImg.addEventListener('click', () => {
      docImg.classList.toggle('is-zoomed');
    });
  }

  // Toast feedback on download
  document.getElementById('viewerDownloadBtn')?.addEventListener('click', () => {
    if (window.showCyberToast) {
      window.showCyberToast(`DOWNLOADING OFFICIAL DOCUMENT // ${cert.downloadFilename}`);
    }
  });

  // Close Handler
  const closeBtn = document.getElementById('certViewerDismissBtn');
  closeBtn?.addEventListener('click', () => {
    modalBackdrop.classList.remove('active');
    modalWindow.classList.remove('modal-wide');
    document.body.style.overflow = '';
  });
}

export function initCertificatesSection() {
  // Bind all triggers for opening certificates
  document.querySelectorAll('[data-cert-open]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const certId = btn.getAttribute('data-cert-open');
      openCertificateViewer(certId);
    });
  });

  // Bind legacy data-cert-view triggers from experience cards
  document.querySelectorAll('[data-cert-view]').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const certId = btn.getAttribute('data-cert-view');
      openCertificateViewer(certId);
    });
  });

  // Bind preview wrap clicks
  document.querySelectorAll('.cert-card-preview-wrap[data-cert-preview-id]').forEach(wrap => {
    wrap.addEventListener('click', () => {
      const certId = wrap.getAttribute('data-cert-preview-id');
      openCertificateViewer(certId);
    });
  });

  // Download feedback toast on card buttons
  document.querySelectorAll('.btn-cert-card-dl').forEach(btn => {
    btn.addEventListener('click', () => {
      const filename = btn.getAttribute('download') || 'Official Certificate';
      if (window.showCyberToast) {
        window.showCyberToast(`DOWNLOADING OFFICIAL DOCUMENT // ${filename}`);
      }
    });
  });

  // Safety fallback: ensure cert cards are promptly revealed on direct navigation or fast scroll
  setTimeout(() => {
    document.querySelectorAll('.cert-gallery-card').forEach(card => {
      const rect = card.getBoundingClientRect();
      if (rect.top < window.innerHeight + 300) {
        card.classList.add('is-revealed');
      }
    });
  }, 300);
}
